"""
boktai_arabic_pixel_font.py - Hand-crafted pixel-perfect Arabic font for Boktai (8x16 4bpp GBA).
Based on bof_pixel_font with strict row 10 baseline unification and distinct dots.
"""
import sys, os, copy
sys.path.insert(0, r"C:\Users\reva4\Desktop\Arabic_BOF_Project")
import bof_pixel_font

GLYPHS = copy.deepcopy(bof_pixel_font.GLYPHS)

def _grid(rows_str):
    lines = [r.strip() for r in rows_str.strip().splitlines()]
    assert len(lines) == 16, f"Expected 16 rows, got {len(lines)}"
    for r in lines:
        assert len(r) == 8, f"Expected 8 cols, got {len(r)} in '{r}'"
    return lines

# 1. Fix Tah (ط) and Zhah (ظ) - Shift down 1 row to align baseline at Row 10
for base_ch in ['ط', 'ظ']:
    for frm in ['iso', 'ini', 'med', 'fin']:
        orig = GLYPHS.get((base_ch, frm))
        if orig:
            # Shift down by 1 row
            shifted = ['........'] + orig[:15]
            # Ensure row 10 connects properly
            r10 = list(shifted[10])
            if frm in ('ini', 'med'):
                for c in range(0, 3): r10[c] = '#'
            if frm in ('fin', 'med'):
                for c in range(5, 8): r10[c] = '#'
            shifted[10] = ''.join(r10)
            GLYPHS[(base_ch, frm)] = shifted

# 2. Fix Alif, Hamza, Ra, Zay final forms - connect at Row 10
for base_ch in ['ا', 'أ', 'إ', 'آ']:
    orig = GLYPHS.get((base_ch, 'fin'))
    if orig:
        g = list(orig)
        g[10] = '...#####'
        g[11] = '........'
        GLYPHS[(base_ch, 'fin')] = g

for base_ch in ['ر', 'ز']:
    orig = GLYPHS.get((base_ch, 'fin'))
    if orig:
        g = list(orig)
        g[10] = '..######'
        g[11] = '....##..'
        GLYPHS[(base_ch, 'fin')] = g

